#!/usr/bin/env python3
"""Write rust/src/tables.rs: the character classes readaloud's Rust half uses,
taken from this Python's own Unicode database.

The Python half and the Rust half must agree on every character: which ones
are letters or digits, which are spaces, what a capital lowers to, how many
terminal cells one takes.  Rust's std follows a newer Unicode than Python
3.12 (15.0), so the Rust side reads these tables instead of std.

    uv run python scripts/gen-unicode-tables.py

Rerun it whenever the pinned Python changes; the output is committed.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "rust" / "src" / "tables.rs"
MAX = 0x110000


def ranges(pred) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start = None
    for cp in range(MAX + 1):
        hit = cp < MAX and pred(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def table(name: str, doc: str, rs: list[tuple[int, int]]) -> str:
    body = "\n".join(f"    (0x{a:04X}, 0x{b:04X})," for a, b in rs)
    return (f"/// {doc}\npub static {name}: [(u32, u32); {len(rs)}] = [\n"
            f"{body}\n];\n")


def rust_str(s: str) -> str:
    return '"' + "".join(f"\\u{{{ord(c):X}}}" for c in s) + '"'


def main() -> None:
    parts = [
        "// @generated by scripts/gen-unicode-tables.py from Python "
        f"{sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.\n"
        "// Do not edit by hand.\n\n",
        table("ALNUM", "str.isalnum(): a letter or digit.",
              ranges(str.isalnum)),
        table("UPPER", "str.isupper().", ranges(str.isupper)),
        table("SPACE", "str.isspace().", ranges(str.isspace)),
        table("ZERO_WIDTH",
              "Combining, or category Mn, Me or Cf: no terminal cell.",
              ranges(lambda c: bool(unicodedata.combining(c))
                     or unicodedata.category(c) in ("Mn", "Me", "Cf"))),
        table("WIDE", "East Asian Width W or F: two terminal cells.",
              ranges(lambda c: unicodedata.east_asian_width(c) in ("W", "F"))),
    ]
    lower = [(cp, chr(cp).lower()) for cp in range(MAX)
             if chr(cp).lower() != chr(cp)]
    body = "\n".join(f"    (0x{cp:04X}, {rust_str(s)})," for cp, s in lower)
    parts.append(f"/// str.lower() of every character it changes.\n"
                 f"pub static LOWER: [(u32, &str); {len(lower)}] = [\n"
                 f"{body}\n];\n")
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
